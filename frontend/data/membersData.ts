export function getAvatarGradientByGender(
  gender: Gender,
  role: MemberRole
): string {
  if (role === "LEADER") {
    return "linear-gradient(135deg, #f59e0b 0%, #b45309 100%)";
  }
  if (gender === "FEMALE") {
    return "linear-gradient(135deg, #ec4899 0%, #be185d 100%)";
  }
  return "linear-gradient(135deg, #38bdf8 0%, #1d4ed8 100%)";
}

